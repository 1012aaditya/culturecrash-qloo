import { chromium } from "playwright";
import { writeFileSync } from "node:fs";
const S = process.env.S, P = process.env.P, base = "http://localhost:3000";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 }, storageState: `${S}/state.json`, permissions: ["clipboard-read", "clipboard-write"] });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto(`${base}/projects/${P}/experiments?new=1`);
await page.fill("#x-hyp", "Messaging centred on daily self-care routines will generate greater audience interest than the current positioning.");
await page.fill("#x-pm", "Click-through rate (%)");
await page.fill("#x-method", "Randomised A/B test (paid social)");
await page.getByRole("button", { name: "Save experiment" }).click();
await page.waitForURL(/experiments\/[0-9a-f-]{36}/);
for (const [variant, value] of [["Control", "1.2"], ["Variant A", "1.8"]]) {
  await page.selectOption("#r-variant", { label: variant.startsWith("Control") ? "Control — current positioning" : "Variant A" });
  await page.fill("#r-value", value); await page.fill("#r-n", "5000");
  await page.getByRole("button", { name: "Record result" }).click(); await page.waitForTimeout(1500);
}
console.log("results rows:", await page.locator("tbody tr").count());
await page.screenshot({ path: `${S}/experiment.png`, fullPage: true });
await page.goto(`${base}/projects/${P}/reports?new=1`);
await page.getByRole("dialog").getByRole("button", { name: "Generate" }).click();
await page.waitForURL(/reports\/[0-9a-f-]{36}/);
await page.waitForTimeout(800);
await page.screenshot({ path: `${S}/report.png` });
const reportUrl = page.url();
const pdf = await page.request.get(`${base}/api/reports/${reportUrl.split("/reports/")[1].split("?")[0]}/pdf`);
console.log("pdf:", pdf.status(), pdf.headers()["content-type"]);
writeFileSync(`${S}/report.pdf`, await pdf.body());
await page.getByRole("button", { name: /^Share/ }).click();
await page.getByRole("button", { name: /Create link/ }).click();
await page.waitForTimeout(1500);
const link = await page.getByLabel("Share link").inputValue();
console.log("share link ok:", /\/reports\/shared\//.test(link));
const anon = await (await browser.newContext()).newPage();
await anon.goto(link);
console.log("anon sees report:", await anon.getByText("Key evidence").count() > 0);
await anon.screenshot({ path: `${S}/shared.png` });
await page.getByRole("button", { name: /Revoke/ }).first().click();
await page.waitForTimeout(1500);
await anon.reload();
console.log("after revoke:", await anon.getByText("This link is not available").count() > 0);
await browser.close();
