import { chromium } from "playwright";
const S = process.env.S;
const base = "http://localhost:3000";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1600, height: 1000 }, storageState: `${S}/state.json` });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto(`${base}/projects/new`);
await page.fill("#name", "Skincare Launch");
await page.fill("input[name=newClientName]", "Lumen Labs");
await page.fill("#brand", "Lumen");
await page.fill("#category", "Skincare");
await page.fill("#market", "India");
await page.click("button[type=submit]");
await page.waitForURL("**/brief**");
await page.fill("#audience", "Gen Z in Indian metros who treat skincare as self-expression");
await page.fill("#objective", "Launch a premium skincare line and build consideration");
await page.fill("#product", "Premium skincare line");
await page.fill("#competitors", "Nykaa, Minimalist");
await page.keyboard.press("Enter");
await page.waitForTimeout(3500);
console.log("save status:", await page.locator("[role=status]").first().innerText());
await page.screenshot({ path: `${S}/brief.png`, fullPage: true });
const url = page.url().replace(/\/brief.*/, "/research");
await page.goto(url);
await page.getByRole("button", { name: /Demo run/ }).first().click();
await page.waitForTimeout(6000);
await page.screenshot({ path: `${S}/research-demo.png` });
await page.getByRole("button", { name: /affinity/ }).first().click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${S}/research-entity.png` });
await page.getByRole("button", { name: /Run again/ }).first().click();
await page.waitForTimeout(9000);
await page.screenshot({ path: `${S}/research-live.png` });
console.log("url", page.url());
await browser.close();
