import { chromium } from "playwright";
const S = process.env.S, P = process.env.P, base = "http://localhost:3000";
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1500, height: 1000 }, storageState: `${S}/state.json` })).newPage();
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto(`${base}/projects/${P}/opportunities`);
await page.getByRole("button", { name: /Generate opportunities/ }).click();
await page.waitForTimeout(3000);
console.log("opps:", await page.locator("li[id^=opp-]").count());
await page.getByRole("button", { name: /^Save$/ }).first().click();
await page.waitForTimeout(1200);
await page.screenshot({ path: `${S}/opps.png` });
await page.goto(`${base}/projects/${P}/strategy`);
await page.getByRole("button", { name: /Generate three directions/ }).click();
await page.waitForTimeout(3500);
console.log("dirs:", await page.locator("article[id^=direction-]").count());
await page.getByRole("button", { name: /^Edit$/ }).first().click();
await page.fill("#ed-coreIdea", "Edited core idea for testing versioning.");
await page.getByRole("button", { name: /Save new version/ }).click();
await page.waitForTimeout(2000);
await page.getByRole("button", { name: /Select direction/ }).first().click();
await page.getByRole("dialog").getByRole("button", { name: /^Select$/ }).click();
await page.waitForTimeout(2000);
await page.screenshot({ path: `${S}/strategy.png` });
await page.getByRole("button", { name: /Generate creative brief/ }).click();
await page.waitForTimeout(3000);
await page.goto(`${base}/projects/${P}/creative-brief`);
await page.getByRole("button", { name: /^Edit$/ }).first().click();
await page.getByRole("textbox", { name: "Background" }).fill("Edited background section.");
await page.getByRole("button", { name: /Save section/ }).click();
await page.waitForTimeout(1500);
console.log("bg:", await page.getByText("Edited background section.").count());
await page.screenshot({ path: `${S}/creative.png` });
const res = await page.request.get(`${base}/api/projects/${P}/creative-brief/export`);
console.log("export:", res.status(), (await res.text()).slice(0, 120).replace(/\n/g, " | "));
await page.goto(`${base}/projects/${P}/strategy/compare`);
await page.screenshot({ path: `${S}/compare.png`, fullPage: true });
await browser.close();
